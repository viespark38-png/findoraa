-- FINDORA DEMO DATABASE SETUP
-- Run this in Supabase Dashboard > SQL Editor > New query.
-- This demo policy allows public visitors to read, post, and update reports.
-- For real school use, replace public UPDATE access with authenticated staff-only policies.

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  report_type text not null check (report_type in ('Lost Item','Found Item')),
  item_name text not null,
  category text not null,
  description text not null,
  item_date date not null,
  location text not null,
  reporter_name text not null,
  contact_info text not null,
  picture text,
  status text not null default 'Available' check (status in ('Available','Claimed','Returned')),
  created_at timestamptz not null default now()
);

alter table public.reports enable row level security;

drop policy if exists "Public can read Findora reports" on public.reports;
create policy "Public can read Findora reports"
on public.reports for select to anon, authenticated using (true);

drop policy if exists "Public can submit Findora reports" on public.reports;
create policy "Public can submit Findora reports"
on public.reports for insert to anon, authenticated with check (true);

drop policy if exists "Demo users can update Findora reports" on public.reports;
create policy "Demo users can update Findora reports"
on public.reports for update to anon, authenticated using (true) with check (true);

-- Enable Realtime so all open Findora pages receive database changes.
do $$
begin
  alter publication supabase_realtime add table public.reports;
exception
  when duplicate_object then null;
  when undefined_object then
    raise notice 'Publication supabase_realtime not found; enable Realtime for reports in Database > Publications.';
end $$;
